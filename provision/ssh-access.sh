#!/usr/bin/env bash

set -euo pipefail
export DEBIAN_FRONTEND=noninteractive

: "${ROLE:?}" "${AUTH_PUBKEY:?}" "${BASTION_IP:?}"

SSH_DIR=/home/vagrant/.ssh
TAG="citybikes-managed"
install -d -m 700 -o vagrant -g vagrant "${SSH_DIR}"
touch "${SSH_DIR}/authorized_keys"

grep -v " ${TAG}\$" "${SSH_DIR}/authorized_keys" > "${SSH_DIR}/authorized_keys.new" || true
echo "${AUTH_PUBKEY} ${TAG}" >> "${SSH_DIR}/authorized_keys.new"
mv "${SSH_DIR}/authorized_keys.new" "${SSH_DIR}/authorized_keys"
chown vagrant:vagrant "${SSH_DIR}/authorized_keys"
chmod 600 "${SSH_DIR}/authorized_keys"

cat > /etc/ssh/sshd_config.d/10-citybikes.conf <<'CONF'
PasswordAuthentication no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
PermitRootLogin no
AllowUsers vagrant
MaxAuthTries 3
LoginGraceTime 30
ClientAliveInterval 120
ClientAliveCountMax 3
X11Forwarding no
AllowAgentForwarding no
# the bastion needs forwarding (ssh -L tunnels go through it)
AllowTcpForwarding yes
LogLevel VERBOSE
CONF
sshd -t

effective=$(sshd -T)
grep -qi '^passwordauthentication no' <<< "${effective}" \
  || { echo "password login is still enabled: another sshd setting overrides ours" >&2; exit 1; }
systemctl reload ssh

if [ "${ROLE}" = "bastion" ]; then
    : "${INTERNAL_KEY_B64:?}" "${PRIVATE_HOSTS:?}"
    (umask 077; base64 -d <<< "${INTERNAL_KEY_B64}" > "${SSH_DIR}/internal_ed25519")
    chown vagrant:vagrant "${SSH_DIR}/internal_ed25519"
    chmod 600 "${SSH_DIR}/internal_ed25519"
    ssh-keygen -y -f "${SSH_DIR}/internal_ed25519" >/dev/null

  {
    echo "# generated by provision/ssh-access.sh"
    echo "Host *"
    echo "  User vagrant"
    echo "  IdentityFile ~/.ssh/internal_ed25519"
    echo "  IdentitiesOnly yes"
    echo "  StrictHostKeyChecking accept-new"
    for pair in ${PRIVATE_HOSTS}; do
      echo "Host ${pair%%=*}"
      echo "  HostName ${pair#*=}"
    done
  } > "${SSH_DIR}/config"
  chown vagrant:vagrant "${SSH_DIR}/config"
  chmod 600 "${SSH_DIR}/config"

    for pair in ${PRIVATE_HOSTS}; do
    echo "${pair#*=} ${pair%%=*} # citybikes" >> /etc/hosts
  done
fi

if [ "${ROLE}" = "target" ]; then
  if ! command -v ufw >/dev/null 2>&1; then
    for i in 1 2 3 4 5; do
      apt-get update && apt-get install -y --no-install-recommends ufw && break
      [ "$i" = 5 ] && exit 1
      sleep 10
    done
  fi
  ufw --force reset >/dev/null
  ufw default allow incoming >/dev/null
  ufw default allow outgoing >/dev/null
  ufw default allow routed >/dev/null

  ufw allow from "${BASTION_IP}" to any port 22 proto tcp comment 'ssh from the bastion' >/dev/null
  ufw allow from 10.0.2.0/24 to any port 22 proto tcp comment 'vagrant (NAT)' >/dev/null
  ufw deny 22/tcp comment 'ssh from everywhere else' >/dev/null
  ufw --force enable >/dev/null
  ufw status | sed 's/^/    /'
fi

echo "ssh-access done (${ROLE}): key login only"
