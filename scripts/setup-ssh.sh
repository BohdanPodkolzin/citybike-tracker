#!/usr/bin/env bash

#   1. creates two key pairs:
#        citybikes_ed25519           YOUR key: lets you log in to the bastion (and only there)
#        citybikes_internal_ed25519  the bastion's key: lets the bastion log in to the other VMs
#   2. writes ./ssh_config so that plain `ssh bastion` works

# Usage: bash scripts/setup-ssh.sh [--install]   (--install adds an Include line to ~/.ssh/config)
set -euo pipefail
cd "$(dirname "$0")/.."

# read a variable from the environment, then .env, then a default (same order as the Vagrantfile)
get() {
  local v="${!1:-}"
  if [ -z "$v" ] && [ -f .env ]; then
    v=$(grep -E "^$1=" .env | tail -1 | cut -d= -f2- | sed -E "s/^[\"']//; s/[\"']$//" || true)
  fi
  echo "${v:-$2}"
}

KEY=$(get SSH_KEY_FILE "$HOME/.ssh/citybikes_ed25519")
KEY="${KEY/#\~/$HOME}"
INTERNAL=$(get SSH_INTERNAL_KEY_FILE "$HOME/.ssh/citybikes_internal_ed25519")
INTERNAL="${INTERNAL/#\~/$HOME}"
LAN=$(get LAN_PREFIX 192.168.0)

make_key() {  # $1 = path, $2 = comment
  if [ ! -f "$1" ]; then
    mkdir -p "$(dirname "$1")" && chmod 700 "$(dirname "$1")"
    ssh-keygen -t ed25519 -N "" -C "$2" -f "$1"
    echo "created $1 (private) and $1.pub"
  else
    echo "using the existing key $1"
  fi
  [ -f "$1.pub" ] || ssh-keygen -y -f "$1" > "$1.pub"
}
make_key "$KEY" "citybikes-user"
make_key "$INTERNAL" "citybikes-bastion"

HERE=$(pwd)
cat > ssh_config <<CONF
# generated by scripts/setup-ssh.sh - do not edit, run the script again
Host bastion
  HostName ${LAN}.54
  User vagrant
  IdentityFile ${KEY}
  IdentitiesOnly yes
  StrictHostKeyChecking accept-new
  UserKnownHostsFile ${HERE}/.ssh_known_hosts

CONF
echo "wrote ${HERE}/ssh_config"

if [ "${1:-}" = "--install" ]; then
  mkdir -p "$HOME/.ssh" && touch "$HOME/.ssh/config"
  LINE="Include ${HERE}/ssh_config"
  if ! grep -qxF "$LINE" "$HOME/.ssh/config"; then
    { echo "$LINE"; cat "$HOME/.ssh/config"; } > "$HOME/.ssh/config.new" && mv "$HOME/.ssh/config.new" "$HOME/.ssh/config"
    chmod 600 "$HOME/.ssh/config"
    echo "added to ~/.ssh/config: $LINE"
  fi
  echo "now: ssh bastion   and then, on the bastion:  ssh ui | ssh fetcher | ssh history | ssh db"
else
  echo "use it with:  ssh -F ssh_config bastion     (or run again with --install to make plain 'ssh bastion' work)"
fi
echo "VMs get recreated with new host keys? delete .ssh_known_hosts"
